import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const configured = Boolean(process.env.E2E_BASE_URL && process.env.E2E_API_URL);
test.skip(!configured, "Set E2E_BASE_URL and E2E_API_URL pointing to an isolated development instance");
const suffix = `${Date.now()}`;
const password = "Browser-test-only-123";
const screenshots = fileURLToPath(new URL("../../docs/screenshots/", import.meta.url));
async function capture(page, name) {
    if (process.env.CAPTURE_SCREENSHOTS !== "1") return;
    await mkdir(screenshots, { recursive: true });
    await expect(page.getByRole("status")).toHaveCount(0, { timeout: 10000 });
    await page.screenshot({ path: `${screenshots}/${name}.png`, fullPage: true });
}
async function login(page, email, pass = password) {
    await page.goto("/login", { waitUntil: "domcontentloaded" });
    await page.getByLabel("Email Address").fill(email);
    await page.getByLabel("Password", { exact: true }).fill(pass);
    await page.getByRole("button", { name: "Login", exact: true }).click();
}
test("public pages, protected-route redirect, failed login, and mobile navigation", async ({ page }) => {
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto("/member/dashboard", { waitUntil: "domcontentloaded" });
    await expect(page).toHaveURL(/\/login$/);
    await capture(page, "login");
    await login(page, "nonexistent@example.invalid", "wrong-password");
    await expect(page.locator(".login-error")).toContainText("invalid email or password");
    await page.goto("/about", { waitUntil: "domcontentloaded" }); await expect(page.locator("main")).toBeVisible();
    await page.goto("/membership-plans", { waitUntil: "domcontentloaded" }); await expect(page.getByText("Basic", { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto("/", { waitUntil: "domcontentloaded" });
    const menu = page.getByRole("button", { name: "Open navigation menu" });
    await menu.click();
    await page.locator("#public-navigation").getByRole("link", { name: "About" }).click();
    await expect(page).toHaveURL(/\/about$/);
    expect(errors).toEqual([]);
});
