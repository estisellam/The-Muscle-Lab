test("Admin dashboard, role navigation, user/plan lists, and trainer/class forms", async ({ page, request }) => {
    test.skip(!process.env.E2E_ADMIN_EMAIL || !process.env.E2E_ADMIN_PASSWORD, "Create a synthetic Admin with npm run dev:admin");
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    page.on("dialog", dialog => dialog.accept());
    await login(page, process.env.E2E_ADMIN_EMAIL, process.env.E2E_ADMIN_PASSWORD);
    await expect(page).toHaveURL(/\/admin\/dashboard$/);
    await expect(page.getByRole("heading", { name: "Admin intelligence dashboard" })).toBeVisible();
    await capture(page, "admin-panel");
    await page.getByRole("link", { name: "Users", exact: true }).click();
    await expect(page.locator(".users-management-card").first()).toBeVisible();
    await page.getByRole("link", { name: "Memberships", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Basic", exact: true })).toBeVisible();
    const account = { first_name: "Synthetic", last_name: "Trainer", email: `browser-trainer-${suffix}@example.invalid`, password };
    expect((await request.post(`${process.env.E2E_API_URL}/auth/register`, { data: account })).status()).toBe(201);
    const auth = await request.post(`${process.env.E2E_API_URL}/auth/login`, { data: { email: process.env.E2E_ADMIN_EMAIL, password: process.env.E2E_ADMIN_PASSWORD } });
    const { token } = await auth.json();
    const users = await (await request.get(`${process.env.E2E_API_URL}/users`, { headers: { Authorization: `Bearer ${token}` } })).json();
    const userId = users.find(u => u.email === account.email).id;
    await page.getByRole("link", { name: "Trainers", exact: true }).click();
    await page.getByLabel("User", { exact: true }).selectOption(userId);
    await page.getByPlaceholder("Specialization").fill("Browser QA");
    await page.getByPlaceholder("Experience Years").fill("2");
    await page.getByRole("button", { name: "Add Trainer", exact: true }).click();
    const trainerCard = page.locator(".users-management-card").filter({ hasText: "Synthetic Trainer" });
    await expect(trainerCard).toContainText("Browser QA");
    await trainerCard.getByRole("button", { name: "Edit", exact: true }).click();
    await expect(page.getByLabel("User", { exact: true })).toHaveValue(userId);
    await expect(page.getByLabel("User", { exact: true })).toBeDisabled();
    await page.getByPlaceholder("Specialization").fill("Updated QA");
    await page.getByRole("button", { name: "Save Changes", exact: true }).click();
    await expect(trainerCard).toContainText("Updated QA");
    const trainers = await (await request.get(`${process.env.E2E_API_URL}/trainers`, { headers: { Authorization: `Bearer ${token}` } })).json();
    const trainerId = trainers.find(t => t.user_id === userId).id;
    await page.getByRole("link", { name: "Classes", exact: true }).click();
    await page.getByLabel("Trainer", { exact: true }).selectOption(trainerId);
    for (const [placeholder, value] of [["Title", `Browser QA ${suffix}`], ["Date (YYYY-MM-DD)", "2026-12-01"], ["Start Time (HH:MM)", "10:00"], ["End Time (HH:MM)", "11:00"], ["Room", "QA"], ["Capacity", "4"]]) await page.getByPlaceholder(placeholder, { exact: true }).fill(value);
    await page.getByRole("button", { name: "Add Class", exact: true }).click();
    const classCard = page.locator(".users-management-card").filter({ hasText: `Browser QA ${suffix}` });
    await expect(classCard).toBeVisible();
    await classCard.getByRole("button", { name: "Edit", exact: true }).click();
    await page.getByPlaceholder("Capacity", { exact: true }).fill("5");
    await page.getByRole("button", { name: "Save Changes", exact: true }).click();
    await expect(classCard).toContainText(/Capacity:\s*5/);
    await classCard.getByRole("button", { name: "Delete", exact: true }).click();
    await expect(classCard).toHaveCount(0);
    await page.getByRole("link", { name: "Trainers", exact: true }).click();
    await trainerCard.getByRole("button", { name: "Delete", exact: true }).click();
    await expect(trainerCard).toHaveCount(0);
    await page.goto("/member/dashboard", { waitUntil: "domcontentloaded" }); await expect(page).toHaveURL(/\/admin\/dashboard$/);
    await page.getByRole("button", { name: "Logout" }).click(); await expect(page).toHaveURL(/\/login$/);
    expect(errors).toEqual([]);
});

test("Admin selectors show lookup errors, recover on retry, and explain an empty trainer list", async ({ page }) => {
    test.skip(!process.env.E2E_ADMIN_EMAIL || !process.env.E2E_ADMIN_PASSWORD, "Create a synthetic Admin first");
    await login(page, process.env.E2E_ADMIN_EMAIL, process.env.E2E_ADMIN_PASSWORD);
    await expect(page).toHaveURL(/\/admin\/dashboard$/);
    await page.route("**/api/trainers", route => route.fulfill({ status: 503, headers: { "Access-Control-Allow-Origin": process.env.E2E_BASE_URL }, contentType: "application/json", body: JSON.stringify({ message: "Lookup unavailable" }) }));
    await page.getByRole("link", { name: "Trainers", exact: true }).click();
    await expect(page.getByRole("alert")).toContainText("Lookup unavailable");
    await expect(page.getByRole("button", { name: "Add Trainer", exact: true })).toBeDisabled();
    await page.unroute("**/api/trainers");
    await page.getByRole("button", { name: "Retry", exact: true }).click();
    await expect(page.getByRole("alert")).toHaveCount(0);
    await expect(page.getByLabel("User", { exact: true })).toBeEnabled();
    await page.route("**/api/trainers", route => route.fulfill({ status: 200, headers: { "Access-Control-Allow-Origin": process.env.E2E_BASE_URL }, contentType: "application/json", body: "[]" }));
    await page.getByRole("link", { name: "Classes", exact: true }).click();
    await expect(page.getByText("Add a trainer before creating a class.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Add Class", exact: true })).toBeDisabled();
});
